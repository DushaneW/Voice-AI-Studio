"""Build desktop icons from the NEXUS geometric waveform mark (requires Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
folder = ROOT / "apps/desktop/src-tauri/icons"
folder.mkdir(exist_ok=True)
image = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
draw = ImageDraw.Draw(image)
draw.rounded_rectangle((32, 32, 992, 992), radius=192, fill="#18211e")
for x, height in [(236, 256), (396, 576), (556, 384), (716, 640)]:
    draw.rounded_rectangle((x, 512-height//2, x+72, 512+height//2), radius=36, fill="#b8dccb")
image.save(folder / "icon.png")
image.save(folder / "icon.ico", sizes=[(n,n) for n in (16,24,32,48,64,128,256)])
image.save(folder / "icon.icns")
for size in (32,128,256):
    image.resize((size,size), Image.Resampling.LANCZOS).save(folder / f"{size}x{size}.png")
(folder / "README.md").write_text("# NEXUS application icons\n\nOriginal geometric waveform mark generated by `scripts/generate_icons.py`. Covered by the repository MIT license. The PNG, ICO and ICNS are source assets for packaging, not generated runtime build output.\n")
