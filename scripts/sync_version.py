"""Generate release version mirrors from runtime/pyproject.toml; CI uses --check."""

import argparse
import json
import re
from pathlib import Path

import tomllib

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    version = tomllib.loads((ROOT / "runtime/pyproject.toml").read_text())["project"][
        "version"
    ]
    if not re.fullmatch(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", version):
        raise SystemExit(
            "Version must be compatible with Python, npm and Cargo release metadata"
        )
    changes = {}
    for name in [
        "apps/desktop/package.json",
        "apps/desktop/package-lock.json",
        "apps/desktop/src-tauri/tauri.conf.json",
    ]:
        path = ROOT / name
        data = json.loads(path.read_text())
        if data["version"] != version or (
            name.endswith("package-lock.json")
            and data["packages"][""]["version"] != version
        ):
            data["version"] = version
            if name.endswith("package-lock.json"):
                data["packages"][""]["version"] = version
            changes[path] = json.dumps(data, indent=2) + "\n"
    for name in [
        "apps/desktop/src-tauri/Cargo.toml",
        "crates/nexus-supervisor/Cargo.toml",
    ]:
        path = ROOT / name
        changes[path] = re.sub(
            r'(?m)^version = "[^"]+"',
            f'version = "{version}"',
            path.read_text(),
            count=1,
        )
    path = ROOT / "Cargo.lock"
    changes[path] = re.sub(
        r'(name = "nexus-(?:desktop|supervisor)"\nversion = ")[^"]+',
        lambda m: m[1] + version,
        path.read_text(),
    )
    changes[ROOT / "runtime/nexus_runtime/_version.py"] = (
        f'# Generated by scripts/sync_version.py; edit runtime/pyproject.toml.\nVERSION = "{version}"\n'
    )
    changes[ROOT / "apps/desktop/src/app/version.ts"] = (
        f'// Generated by scripts/sync_version.py; edit runtime/pyproject.toml.\nexport const VERSION = "{version}";\n'
    )
    stale = [
        path
        for path, content in changes.items()
        if not path.exists() or path.read_text() != content
    ]
    if args.check and stale:
        raise SystemExit(
            "Version mirrors stale: "
            + ", ".join(str(p.relative_to(ROOT)) for p in stale)
        )
    for path in stale:
        path.write_text(changes[path])
    print(
        f"Version {version}: {len(stale)} mirrors updated"
        if not args.check
        else f"Version {version}: mirrors consistent"
    )


if __name__ == "__main__":
    main()
